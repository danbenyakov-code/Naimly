/** כל השאלות ברשימה אחת — ל-FAQPage ב-JSON-LD ול-llms.txt. */
export const faqs = faqGroups.flatMap((group) => group.items);

const organizationId = `${brand.siteUrl}/#organization`;

/** ה-JSON-LD של דף הבית: ארגון, אתר, מוצר ושאלות נפוצות. */
export function homeJsonLd() {
  return {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "Organization",
        "@id": organizationId,
        name: brand.name,
        alternateName: brand.hebrewName,
        url: brand.siteUrl,
        logo: `${brand.siteUrl}/icon.svg`,
        email: brand.supportEmail,
        description: productDefinition,
        areaServed: { "@type": "Country", name: "Israel" },
        sameAs: socialLinks.map((social) => social.url),
        contactPoint: {
          "@type": "ContactPoint",
          contactType: "customer support",
          email: brand.supportEmail,
          telephone: brand.supportWhatsapp ? `+${brand.supportWhatsapp}` : undefined,
          availableLanguage: ["he", "en"],
          areaServed: "IL",
        },
      },
      {
        "@type": "WebSite",
        "@id": `${brand.siteUrl}/#website`,
        name: brand.name,
        alternateName: brand.hebrewName,
        url: brand.siteUrl,
        inLanguage: "he-IL",
        publisher: { "@id": organizationId },
      },
      {
        "@type": "SoftwareApplication",
        name: `${brand.name} — כרטיס ביקור דיגיטלי ומיני סייט`,
        description: homeDescription,
        applicationCategory: "BusinessApplication",
        operatingSystem: "Web",
        inLanguage: "he-IL",
        url: brand.siteUrl,
        publisher: { "@id": organizationId },
        offers: paidPlans.map((plan) => ({
          "@type": "Offer",
          name: plan.name,
          description: plan.description,
          url: `${brand.siteUrl}/pricing`,
          priceSpecification: {
            "@type": "UnitPriceSpecification",
            price: plan.price,
            priceCurrency: "ILS",
            unitText: "MONTH",
            valueAddedTaxIncluded: false,
          },
        })),
      },
      {
        "@type": "FAQPage",
        mainEntity: faqs.map(([question, answer]) => ({
          "@type": "Question",
          name: question,
          acceptedAnswer: { "@type": "Answer", text: answer },
        })),
      },
    ],
  };
}

/** סימון בטוח של JSON-LD בתוך <script> — מונע סגירת תגית מתוך הטקסט. */
export function jsonLdScript(data: unknown) {
  return { __html: JSON.stringify(data).replace(/</g, "\\u003c") };
}

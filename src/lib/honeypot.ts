/**
 * מלכודת ספאם — שם השדה והתנהגותו.
 *
 * QA-006 · הממצא דיווח ששדה ה-honeypot "מוצג למשתמש". בבדיקה בייצור הוא
 * אינו מוצג: `sr-only` קיים ותקין ב-CSS, ויש `aria-hidden` ו-`tabindex="-1"`.
 *
 * אבל הבדיקה חשפה תקלה חמורה יותר באותו מקום. השדות נקראו `website`
 * ו-`company` — **שני אסימוני autofill תקניים של הדפדפן** (`url` ו-
 * `organization`). משתמש עם מילוי אוטומטי פעיל קיבל אותם מלאים בלי
 * לדעת, השרת ראה ערך בשדה המלכודת, והחזיר `{ ok: true }` **בלי לשמור
 * את הפנייה**.
 *
 * כלומר: לקוח אמיתי ראה "הפנייה נשלחה", ושום ליד לא נשמר ושום מייל לא
 * יצא. זה מסביר גם את QA-033 — ההתראה לא הגיעה כי לא היה ליד.
 *
 * שם שאינו אסימון מוכר אינו נגרר למילוי אוטומטי. זו ההגנה האמיתית;
 * `sr-only` מסתיר מהעין, אך אינו מונע מהדפדפן למלא.
 */

/** שם שדה המלכודת. בכוונה אינו דומה לשום אסימון autofill. */
export const HONEYPOT_FIELD = "naimly_hp_ref";

/**
 * תכונות השדה.
 *
 * ארבע שכבות, וכל אחת נחוצה:
 *   aria-hidden  — מחוץ לעץ הנגישות, כך שקורא מסך אינו מכריז אותו.
 *   tabIndex -1  — מחוץ לסדר ה-Tab, כך שניווט במקלדת אינו נתקע בו.
 *   sr-only      — מוסתר מהעין בלי display:none, שבוטים מזהים ומדלגים.
 *   autoComplete — רמז נוסף לדפדפן, מעבר לשם שאינו מוכר.
 */
export const honeypotInputProps = {
  name: HONEYPOT_FIELD,
  tabIndex: -1,
  autoComplete: "off",
  "aria-hidden": true as const,
} as const;

/**
 * האם הבקשה נראית כבוט.
 *
 * מקבל את הערך של שדה המלכודת בלבד. השמות הישנים אינם נבדקים יותר
 * בכוונה: הם נגררו למילוי אוטומטי, ובדיקתם הייתה ממשיכה לדחות לקוחות
 * אמיתיים שדף ישן נשמר אצלם במטמון.
 */
export function looksLikeBot(value: unknown): boolean {
  return typeof value === "string" && value.trim().length > 0;
}

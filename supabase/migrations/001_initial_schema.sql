create policy "profiles_read_own" on public.profiles for select to authenticated using (id = auth.uid());
create policy "profiles_update_own" on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());
create policy "profiles_admin_all" on public.profiles for all to authenticated using (public.is_admin()) with check (public.is_admin());

create policy "cards_public_read_published" on public.cards for select to anon, authenticated using (is_published = true or user_id = auth.uid() or public.is_admin());
create policy "cards_owner_insert" on public.cards for insert to authenticated with check (user_id = auth.uid());
create policy "cards_owner_update" on public.cards for update to authenticated using (user_id = auth.uid() or public.is_admin()) with check (user_id = auth.uid() or public.is_admin());
create policy "cards_owner_delete" on public.cards for delete to authenticated using (user_id = auth.uid() or public.is_admin());

create policy "events_owner_read" on public.card_events for select to authenticated using (exists(select 1 from public.cards where cards.id = card_events.card_id and (cards.user_id = auth.uid() or public.is_admin())));
create policy "leads_owner_read" on public.leads for select to authenticated using (exists(select 1 from public.cards where cards.id = leads.card_id and (cards.user_id = auth.uid() or public.is_admin())));
create policy "leads_owner_update" on public.leads for update to authenticated using (exists(select 1 from public.cards where cards.id = leads.card_id and (cards.user_id = auth.uid() or public.is_admin()))) with check (exists(select 1 from public.cards where cards.id = leads.card_id and (cards.user_id = auth.uid() or public.is_admin())));
create policy "subscriptions_read_own" on public.subscriptions for select to authenticated using (user_id = auth.uid() or public.is_admin());
create policy "audit_admin_read" on public.admin_audit_log for select to authenticated using (public.is_admin());
create policy "payment_events_admin_read" on public.payment_events for select to authenticated using (public.is_admin());

